#include <iostream>
using namespace std;
 //Utilizacion de bucle  do while en el cual se debe definir el numero en el 
 //que se debe comenzar así como el aumento de la variable al pasar por el bucle y se ejecuta primero los procesos y despues se decide si seguir o no
int main (){
    int i =1;
    //bucle  do while de 1 hasta 5
    do {
        cout << i << "";
        ++i;
    }while(i<=5);
    
    
     return 0;
}   
   