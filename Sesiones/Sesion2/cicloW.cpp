#include <iostream>
using namespace std;
 //Utilizacion de bucle while en el cual se debe definir el numero en el 
 //que se debe comenzar así como el aumento de la variable al pasar por el bucle
int main (){
    int i =1;
    //bucle  while de 1 hasta 5
    while(i<=5){
        cout << i << "";
        ++i;
    }
     return 0;
}   
   